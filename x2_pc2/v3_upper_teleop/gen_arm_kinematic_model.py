#!/usr/bin/env python3
"""Generate the kinematics-only X2 MJCF module shipped to PC2 for mink.

The mink arm solver builds its model with ``mujoco.MjSpec.from_file`` on
``gear_sonic/data/assets/robot_description/mjcf/x2_ultra.xml``.  On PC2 that
tree does not exist, and copying it is not an option: the MJCF references
66 MB of meshes.  Kinematics do not need any of them -- bodies, joints,
poses and axes are enough -- so this tool strips every geom / site / mesh /
texture / material / actuator / sensor / camera / light / tendon /
equality / keyframe and gives each moving body a dummy inertial (MuJoCo
refuses to compile a moving body with zero mass), leaving a ~13 KB model
that is byte-for-byte the same kinematic tree.

The result is written as a Python module (``x2_arm_kinematic.py``) instead
of a .xml file on purpose: the PC2 ``czq_examples`` package is an
ament_python/setuptools package, and ``build_py`` copies *.py files but not
arbitrary data files.  A sibling module is therefore guaranteed to land in
``install/.../site-packages/czq_examples/`` with no setup.py change.

Usage:
    .venv/bin/python gen_arm_kinematic_model.py            # write the module
    .venv/bin/python gen_arm_kinematic_model.py --check    # fail on drift
    .venv/bin/python gen_arm_kinematic_model.py --verify MODULE
        # no mujoco needed: only check MODULE's SOURCE_SHA256 against the MJCF

Why the hash matters: the generator is the only thing that can see the
source MJCF.  When the description changes, the hash check in
``build_bundle.sh`` refuses a stale module rather than shipping a model
whose joint ranges or body poses have quietly drifted from the plant.
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT_MJCF = (
    HERE.parents[1]
    / "gear_sonic"
    / "data"
    / "assets"
    / "robot_description"
    / "mjcf"
    / "x2_ultra.xml"
)
DEFAULT_OUT = HERE / "x2_arm_kinematic.py"

# Collections whose entries carry geometry or plant behaviour.  None of them
# contributes to the kinematic tree; leaving any one in place drags an asset
# reference (or an unused actuator) back into the file.
_DROP_COLLECTIONS = (
    "geoms",
    "sites",
    "actuators",
    "sensors",
    "cameras",
    "lights",
    "equalities",
    "tendons",
    "keyframes",
    "meshes",
    "textures",
    "materials",
)

# What MuJoCo needs for a body that has no mass of its own; kinematics only
# reads poses and axes, never mass, so any positive value is fine.
_DUMMY_MASS = 1.0
_DUMMY_INERTIA = (0.01, 0.01, 0.01)


def _sha256(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def build_xml(mjcf: pathlib.Path) -> str:
    """Return the kinematics-only MJCF text for ``mjcf``."""
    import mujoco

    spec = mujoco.MjSpec.from_file(str(mjcf))
    for attr in _DROP_COLLECTIONS:
        collection = getattr(spec, attr, None)
        if collection is None:
            continue
        for element in list(collection):
            spec.delete(element)

    for body in spec.bodies:
        if body.name == "world":
            continue
        body.mass = _DUMMY_MASS
        body.inertia = _DUMMY_INERTIA

    # Compile now: a model that does not compile must never reach the robot,
    # and the error names the exact body when the MJCF outgrew this stripper.
    model = spec.compile()
    assert model.nq > 0 and model.nv > 0
    xml = spec.to_xml()
    if not xml.endswith("\n"):
        xml += "\n"
    return xml


def render_module(xml: str, source_sha256: str, mjcf: pathlib.Path) -> str:
    try:
        rel = mjcf.resolve().relative_to(HERE.parents[1])
    except ValueError:  # outside the repo (tests, one-off MJCFs)
        rel = mjcf
    return f'''"""Kinematics-only X2 MJCF for the mink arm IK on PC2 (GENERATED).

Generated by ``x2_pc2/v3_upper_teleop/gen_arm_kinematic_model.py`` from
``{rel}``
(source sha256 ``{source_sha256}``).

Every geom / site / mesh / texture / material / actuator / sensor / camera /
light / tendon / equality / keyframe is removed and each moving body carries
a dummy inertial, so the file needs no mesh assets while keeping the exact
same bodies, joint names, joint ranges, axes and relative poses as the plant
MJCF.  The mink backend only reads kinematics.

Regenerate this module whenever the source MJCF changes; the bundle build
refuses a stale one (SOURCE_SHA256 is checked against the MJCF).  Do not
edit by hand.
"""

SOURCE_SHA256 = "{source_sha256}"

XML = r"""{xml}"""
'''


def _read_source_sha(module: pathlib.Path) -> str:
    text = module.read_text(encoding="utf-8")
    match = re.search(r'^SOURCE_SHA256 = "([0-9a-f]{64})"$', text, re.MULTILINE)
    if match is None:
        raise SystemExit(f"{module}: no SOURCE_SHA256 found; regenerate it")
    return match.group(1)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--mjcf", type=pathlib.Path, default=DEFAULT_MJCF, help="source X2 MJCF")
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT, help="module to write")
    ap.add_argument(
        "--check",
        action="store_true",
        help="do not write; fail if --out differs from a fresh generation",
    )
    ap.add_argument(
        "--verify",
        type=pathlib.Path,
        metavar="MODULE",
        help="no mujoco needed: check MODULE's SOURCE_SHA256 against --mjcf",
    )
    args = ap.parse_args(argv)

    if not args.mjcf.is_file():
        raise SystemExit(f"source MJCF not found: {args.mjcf}")
    sha = _sha256(args.mjcf)

    if args.verify is not None:
        got = _read_source_sha(args.verify)
        if got != sha:
            print(
                f"[kinematic] STALE: {args.verify} was generated from a different "
                f"MJCF (module {got[:12]} != source {sha[:12]}); regenerate it",
                file=sys.stderr,
            )
            return 1
        print(f"[kinematic] {args.verify} matches the source MJCF ({sha[:12]})")
        return 0

    xml = build_xml(args.mjcf)
    text = render_module(xml, sha, args.mjcf)

    if args.check:
        old = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        if old != text:
            print(
                f"[kinematic] STALE: {args.out} differs from a fresh generation; "
                "rerun without --check",
                file=sys.stderr,
            )
            return 1
        print(f"[kinematic] {args.out} is current ({sha[:12]})")
        return 0

    args.out.write_text(text, encoding="utf-8")
    n_bodies = xml.count("<body ")
    n_joints = xml.count("<joint ")
    print(
        f"[kinematic] wrote {args.out} ({len(text)} bytes, {n_bodies} bodies, "
        f"{n_joints} joints, source {sha[:12]})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
